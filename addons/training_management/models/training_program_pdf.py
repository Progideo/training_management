import hashlib
import io

from lxml import etree, html
from markupsafe import Markup

from odoo import api, fields, models
from odoo.exceptions import AccessError, ValidationError


class TrainingProgramPdf(models.Model):
    _inherit = "training.program.version"  # pylint: disable=consider-merging-classes-inherited  # catalogue PDF generation is independent of private S05 support versions

    category_id = fields.Many2one(related="course_id.category_id", string="Category")
    pdf_attachment_id = fields.Many2one(
        "ir.attachment", string="Programme PDF", readonly=True, copy=False, ondelete="restrict"
    )
    pdf_generated_by_id = fields.Many2one(
        "res.users", string="PDF Generated By", readonly=True, copy=False, ondelete="restrict"
    )
    pdf_generated_at = fields.Datetime(string="PDF Generated On", readonly=True, copy=False)
    pdf_sha256 = fields.Char(string="PDF Fingerprint", readonly=True, copy=False)
    pdf_language_code = fields.Char(string="PDF Language", readonly=True, copy=False)
    pdf_reconstructed = fields.Boolean(string="Reconstructed PDF", readonly=True, copy=False)
    pdf_legacy = fields.Boolean(string="Historical Programme", readonly=True, copy=False)

    @api.private
    def _pdf_content_html(self, title):
        """Keep the section label with the first chapter, without a page-sized box."""
        self.ensure_one()
        self.check_access("read")
        root = html.fragment_fromstring(self.content_formatted or "<p></p>", create_parent="div")
        if root.text and root.text.strip():
            paragraph = html.Element("p")
            paragraph.text, root.text = root.text, None
            root.insert(0, paragraph)
        first = next((node for node in root if isinstance(node.tag, str)), None)
        if first is not None and first.tag in {"h1", "h2", "h3", "h4", "h5", "h6"}:
            first.tag = "h2"
            first.text = title + " — " + (first.text or "")
        else:
            heading = html.Element("h2")
            heading.text = title
            root.insert(0, heading)
        # Keep only the label and the first short item together. Keeping the
        # entire outline together can create a blank page in the native engine.
        intro = html.Element("div")
        intro.append(root[0])
        if len(root):
            first_body = root[0]
            if first_body.tag in {"ul", "ol"} and len(first_body):
                lead = html.Element(first_body.tag, dict(first_body.attrib))
                lead.append(first_body[0])
                intro.append(lead)
                if first_body.tag == "ol":
                    try:
                        first_body.set("start", str(int(first_body.get("start", "1")) + 1))
                    except ValueError:
                        first_body.set("start", "2")
                if not len(first_body):
                    root.remove(first_body)
            else:
                intro.append(first_body)
        if len(intro.text_content()) < 1400:
            intro.set("class", "programme-intro")
        root.insert(0, intro)
        return Markup("".join(etree.tostring(node, encoding="unicode", method="html") for node in root))

    def _audit_fields(self):
        return super()._audit_fields() | {
            "pdf_attachment_id",
            "pdf_generated_by_id",
            "pdf_generated_at",
            "pdf_sha256",
            "pdf_language_code",
            "pdf_reconstructed",
            "pdf_legacy",
        }

    def _check_complete(self):
        result = super()._check_complete()
        for program in self:
            if not program.pdf_legacy and not program.course_id.category_id:
                raise ValidationError(
                    self.env._("Choose the course category before validating or publishing its programme.")
                )
        return result

    @api.private
    def _require_pdf_coordinator(self):
        self.check_access("write")
        if not self.env.su and not self.env.user.has_group("training_management.group_training_coordinator"):
            raise AccessError(self.env._("Only the training coordinator may generate the programme PDF."))

    @api.private
    def _render_program_pdf(self, draft=False, reconstructed=False):
        self.ensure_one()
        self.check_access("read")
        program = self.with_company(self.company_id).with_context(lang=self.language_id.code or self.env.lang)
        report = program.env.ref("training_management.action_programme_pdf_preview")
        engine = program.env["ir.actions.report"]
        html = engine._render_template(
            "training_management.programme_pdf_document",
            {
                "docs": program,
                "draft": draft,
                "reconstructed": reconstructed,
                "generated_at": fields.Datetime.now(),
            },
        ).decode()
        # Use Odoo's exact Community report engine, with self-contained HTML:
        # no HTTP asset fetch, no HTML fallback during tests, no report cache.
        raw = engine._run_pdf_engine_without_processing(engine._get_pdf_engine(report), [html], report_ref=report)
        if not raw.startswith(b"%PDF-"):
            raise ValidationError(self.env._("PDF generation failed. The programme has not been validated."))
        return raw

    @api.private
    def _freeze_program_pdf(self, reconstructed=False):
        self._require_pdf_coordinator()
        for program in self:
            if program.pdf_sha256 or program.pdf_attachment_id:
                raise ValidationError(self.env._("The reference PDF already exists and cannot be replaced."))
            raw = program._render_program_pdf(reconstructed=reconstructed)
            attachment = self.env["ir.attachment"]._create_programme_pdf(program, raw)
            # Only this private path writes protected metadata. No context flag
            # permits a caller to bypass the programme's immutable write method.
            program._store_pdf_metadata(
                {
                    "pdf_attachment_id": attachment.id,
                    "pdf_generated_by_id": self.env.uid,
                    "pdf_generated_at": fields.Datetime.now(),
                    "pdf_sha256": hashlib.sha256(raw).hexdigest(),
                    "pdf_language_code": program.language_id.code,
                    "pdf_reconstructed": reconstructed,
                }
            )

    @api.private
    def _reference_pdf(self):
        self.ensure_one()
        self.env["training.document.policy"]._check_read(self)
        authorized = self.sudo()
        attachment = authorized.pdf_attachment_id
        if not attachment or not authorized.pdf_sha256:
            raise ValidationError(
                self.env._("No reference PDF is available. Ask the coordinator to check this programme.")
            )
        # Native attachment streaming can arrive with sudo/token. Metadata is
        # checked after the caller's explicit parent authorization above.
        stored = attachment.sudo()
        if (
            stored.training_program_id != self
            or stored.res_model != self._name
            or stored.res_id != self.id
            or stored.public
            or stored.access_token
            or hashlib.sha256(stored.raw or b"").hexdigest() != authorized.pdf_sha256
        ):
            raise ValidationError(
                self.env._("The reference PDF is missing or altered. It will not be regenerated automatically.")
            )
        return attachment

    def action_download_pdf(self):
        attachment = self._reference_pdf()
        return {"type": "ir.actions.act_url", "url": f"/web/content/{attachment.id}?download=true", "target": "self"}

    def action_preview_pdf(self):
        self.ensure_one()
        self.check_access("read")
        if self.state != "draft":
            return self.action_download_pdf()
        return self.env.ref("training_management.action_programme_pdf_preview").report_action(self, config=False)

    def action_reconstruct_pdf(self):
        self._require_pdf_coordinator()
        self._lock_courses()
        self.lock_for_update()
        self.invalidate_recordset()
        with self.env.cr.savepoint():
            for program in self:
                if program.pdf_attachment_id or program.pdf_sha256:
                    program._reference_pdf()
                    continue
                if not program.pdf_legacy or program.state == "draft":
                    raise ValidationError(
                        self.env._("Only historical programmes without a reference PDF can be reconstructed.")
                    )
                program._freeze_program_pdf(reconstructed=True)
        return True


class ProgrammePdfPreview(models.AbstractModel):
    _name = "report.training_management.programme_pdf_document"
    _description = "Draft Programme PDF"

    @api.model
    def _get_report_values(self, docids, data=None):
        programs = self.env["training.program.version"].browse(docids)
        programs.check_access("read")
        if not programs or any(program.state != "draft" for program in programs):
            raise ValidationError(self.env._("Use Download Programme PDF to obtain the preserved reference document."))
        # Never trust report URL data/context to remove the draft watermark.
        return {"docs": programs, "draft": True, "reconstructed": False, "generated_at": fields.Datetime.now()}


class ProgrammePdfReport(models.Model):
    _inherit = "ir.actions.report"

    def _render_qweb_pdf(self, report_ref, res_ids=None, data=None):
        report = self._get_report(report_ref)
        if report.report_name != "training_management.programme_pdf_document":
            return super()._render_qweb_pdf(report_ref, res_ids=res_ids, data=data)
        programs = self.env["training.program.version"].browse([res_ids] if isinstance(res_ids, int) else res_ids)
        programs.check_access("read")
        if not programs:
            raise ValidationError(self.env._("Select a programme to print."))
        streams = []
        for program in programs:
            raw = (
                program._render_program_pdf(draft=True)
                if program.state == "draft"
                else bytes(program._reference_pdf().raw)
            )
            streams.append(raw)
        if len(streams) == 1:
            return streams[0], "pdf"
        with self._merge_pdfs([io.BytesIO(raw) for raw in streams]) as merged:
            return merged.getvalue(), "pdf"
