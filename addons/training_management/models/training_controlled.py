import json

from odoo import api, fields, models
from odoo.exceptions import AccessError, ValidationError


TERMINAL = {"closed", "cancelled", "replaced", "abandoned"}


class TrainingOperation(models.Model):
    _name = "training.operation"
    _description = "Training Operation History"
    _order = "id desc"

    delivery_id = fields.Many2one("training.delivery", required=True, ondelete="restrict", index=True)
    company_id = fields.Many2one(related="delivery_id.company_id", store=True)
    model_name = fields.Char(required=True)
    record_id = fields.Integer(required=True)
    record_label = fields.Char(string="Record", default="Training record", required=True)
    changes = fields.Text(string="Changes", compute="_compute_changes")
    actor_id = fields.Many2one("res.users", required=True, ondelete="restrict")
    occurred_at = fields.Datetime(required=True)
    reason = fields.Text()
    before = fields.Text()
    after = fields.Text()

    def _compute_changes(self):
        for row in self:
            before = json.loads(row.before or "{}")
            after = json.loads(row.after or "{}")
            descriptions = self.env[row.model_name].fields_get(list(after))
            lines = []
            for key, value in after.items():
                description = descriptions.get(key, {})
                label = description.get("string", key)
                selection = dict(description.get("selection", []))
                if description.get("type") == "many2one":
                    # The record label is captured separately; don't expose raw
                    # relation ids or follow a possibly reassigned historical link.
                    lines.append(label)
                else:
                    old = selection.get(before.get(key), before.get(key, "—"))
                    new = selection.get(value, value)
                    lines.append(f"{label}: {old} → {new}")
            row.changes = "\n".join(lines)

    @api.model_create_multi
    def create(self, vals_list):
        raise AccessError(self.env._("Operation history is generated by the server."))

    def write(self, vals):
        raise AccessError(self.env._("Operation history is immutable."))

    def unlink(self):
        raise AccessError(self.env._("Operation history is immutable."))

    @api.private
    def _record(self, record, before, after, reason):
        record._require_coordinator()
        delivery = record if record._name == "training.delivery" else record.delivery_id
        # Narrow elevation: append a server-authored audit row after access checks.
        # No history create/write/unlink permission is granted to business users.
        return super(TrainingOperation, self.sudo()).create({
            "delivery_id": delivery.id, "model_name": record._name,
            "record_id": record.id, "record_label": record.display_name, "actor_id": self.env.uid,
            "occurred_at": fields.Datetime.now(), "reason": reason or False,
            "before": json.dumps(before, default=str, sort_keys=True),
            "after": json.dumps(after, default=str, sort_keys=True),
        })


class TrainingControlled(models.AbstractModel):
    _name = "training.controlled"
    _description = "Controlled Training Record"

    change_reason = fields.Text(string="Reason for Next Action", copy=False)

    @api.private
    def _require_coordinator(self):
        self.check_access("write" if self else "create")
        if not self.env.su and not self.env.user.has_group("training_management.group_training_coordinator"):
            raise AccessError(self.env._("Only a training coordinator may perform this operation."))

    @api.private
    def _reason(self):
        self.ensure_one()
        reason = (self.change_reason or "").strip()
        if not reason:
            raise ValidationError(self.env._("Enter a reason before performing this action."))
        return reason

    @api.private
    def _store(self, values, reason=False):
        self.ensure_one()
        before = {key: self[key].id if self._fields[key].type == "many2one" else self[key] for key in values}
        result = super(TrainingControlled, self).write(values)
        self.env["training.operation"]._record(self, before, values, reason)
        return result

    def unlink(self):
        raise ValidationError(self.env._("Keep training records and their history; use the cancellation workflow."))
