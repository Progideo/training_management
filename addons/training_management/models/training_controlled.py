import json

from odoo import api, fields, models
from odoo.exceptions import AccessError, ValidationError
from odoo.tools.misc import format_date, format_datetime


MAIL_FIELDS = {"message_main_attachment_id"}
TERMINAL = {"closed", "cancelled", "replaced", "abandoned", "postponed"}


class TrainingOperation(models.Model):
    _name = "training.operation"
    _description = "Training Operation History"
    _order = "id desc"

    delivery_id = fields.Many2one("training.delivery", required=True, ondelete="restrict", index=True)
    company_id = fields.Many2one(related="delivery_id.company_id", store=True)
    model_name = fields.Char(required=True)
    record_id = fields.Integer(required=True)
    record_label = fields.Char(string="Record", default="Training record", required=True)
    changes = fields.Text(compute="_compute_changes")
    actor_id = fields.Many2one("res.users", required=True, ondelete="restrict")
    occurred_at = fields.Datetime(required=True)
    reason = fields.Text()
    before = fields.Text()
    after = fields.Text()
    # Old and new display labels of linked records, captured when the row is
    # written, so that history never follows a link that was reassigned later.
    labels = fields.Text()

    @api.private
    def _format_change_value(self, value, description):
        if value is None:
            return "—"
        kind = description.get("type")
        if kind == "boolean":
            return self.env._("Yes") if value else self.env._("No")
        if value is False or value == "":
            return "—"
        if kind == "datetime":
            return format_datetime(
                self.env, fields.Datetime.to_datetime(value), tz=self.env.context.get("tz") or self.env.user.tz or "UTC"
            )
        if kind == "date":
            return format_date(self.env, fields.Date.to_date(value))
        return dict(description.get("selection", [])).get(value, value)

    @api.depends("before", "after", "model_name")
    @api.depends_context("lang", "tz", "uid")
    def _compute_changes(self):
        for row in self:
            before = json.loads(row.before or "{}")
            after = json.loads(row.after or "{}")
            captured = json.loads(row.labels or "{}")
            descriptions = self.env[row.model_name].fields_get(list(after)) if after else {}
            lines = []
            for key, value in after.items():
                description = descriptions.get(key, {})
                label = description.get("string", key)
                if description.get("type") == "many2one":
                    # Never expose raw relation ids or follow a possibly
                    # reassigned historical link: use the labels captured then.
                    names = captured.get(key)
                    if names:
                        lines.append(f"{label}: {names.get('before') or '—'} → {names.get('after') or '—'}")
                    else:
                        lines.append(label)
                else:
                    old = row._format_change_value(before.get(key), description)
                    new = row._format_change_value(value, description)
                    lines.append(f"{label}: {old} → {new}")
            row.changes = "\n".join(lines)

    @api.model_create_multi
    def create(self, vals_list):  # pylint: disable=method-required-super  # training records are changed only through their controlled actions
        raise AccessError(self.env._("Operation history is generated by the server."))

    def write(self, vals):  # pylint: disable=method-required-super  # training records are changed only through their controlled actions
        raise AccessError(self.env._("Operation history is immutable."))

    def unlink(self):  # pylint: disable=method-required-super  # training records are changed only through their controlled actions
        raise AccessError(self.env._("Operation history is immutable."))  # pylint: disable=no-raise-unlink  # training records are never deleted: refusal is intended

    @api.private
    def _record(self, record, before, after, reason):
        record._require_coordinator()
        delivery = record if record._name == "training.delivery" else record.delivery_id
        labels = {}
        for key in set(before) | set(after):
            field = record._fields.get(key)
            if field is not None and field.type == "many2one":
                # Display names only, read narrowly: the actor may not read the linked record.
                comodel = record.env[field.comodel_name].sudo()
                labels[key] = {
                    side: (comodel.browse(values[key]).exists().display_name or None) if values.get(key) else None
                    for side, values in (("before", before), ("after", after))
                }
        # Narrow elevation: append a server-authored audit row after access checks.
        # No history create/write/unlink permission is granted to business users.
        return super(TrainingOperation, self.sudo()).create(  # pylint: disable=super-method-mismatch  # deliberate bypass of the controlled write, see _store
            {
                "delivery_id": delivery.id,
                "model_name": record._name,
                "record_id": record.id,
                "record_label": record.display_name,
                "actor_id": self.env.uid,
                "occurred_at": fields.Datetime.now(),
                "reason": reason or False,
                "before": json.dumps(before, default=str, sort_keys=True),
                "after": json.dumps(after, default=str, sort_keys=True),
                "labels": json.dumps(labels, sort_keys=True) if labels else False,
            }
        )


class TrainingControlled(models.AbstractModel):
    _name = "training.controlled"
    _description = "Controlled Training Record"

    # Public actions that accept a reason from the generic reason assistant.
    # Each concrete model lists its own; the assistant refuses anything else.
    _reason_actions = ()

    @api.private
    def _require_coordinator(self):
        self.check_access("write" if self else "create")
        if not self.env.su and not self.env.user.has_group("training_management.group_training_coordinator"):
            raise AccessError(self.env._("Only a training coordinator may perform this operation."))

    @api.private
    def _write_technical(self, vals):
        """Write the mail bookkeeping values directly and return the business values.

        Chatter and activities store technical fields on the record; they are
        neither business changes nor journal material.
        """
        technical = {key: vals[key] for key in vals if key in MAIL_FIELDS}
        if technical:
            super(TrainingControlled, self).write(technical)  # pylint: disable=super-method-mismatch  # deliberate bypass of the controlled write, see _store
        return {key: value for key, value in vals.items() if key not in MAIL_FIELDS}

    @api.private
    def _require_reason(self, reason):
        # Every motivated action receives its own reason; nothing is kept on
        # the record afterwards. The history keeps the evidence.
        reason = (reason or "").strip()
        if not reason:
            raise ValidationError(self.env._("Enter a reason before performing this action."))
        return reason

    @api.private
    def _reason_labels(self):
        return {}

    @api.private
    def _store(self, values, reason=False):
        self.ensure_one()
        before = {key: self[key].id if self._fields[key].type == "many2one" else self[key] for key in values}
        result = super(TrainingControlled, self).write(values)  # pylint: disable=super-method-mismatch  # deliberate bypass of the controlled write, see _store
        self.env["training.operation"]._record(self, before, values, reason)
        return result

    def action_open_reason(self):
        """Open the generic reason assistant for the action named in the context."""
        self._require_coordinator()
        action = self.env.context.get("reason_action")
        if action not in self._reason_actions:
            raise ValidationError(self.env._("This action does not accept a reason from the assistant."))
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("Reason for the Action"),
            "res_model": "training.action.reason",
            "view_mode": "form",
            "target": "new",
            "context": {
                "default_res_model": self._name,
                "default_res_ids": ",".join(map(str, self.ids)),
                "default_action_name": action,
            },
        }

    def unlink(self):  # pylint: disable=method-required-super  # training records are changed only through their controlled actions
        raise ValidationError(self.env._("Keep training records and their history; use the cancellation workflow."))  # pylint: disable=no-raise-unlink  # training records are never deleted: refusal is intended
