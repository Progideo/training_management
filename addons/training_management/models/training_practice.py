"""P11: private post-training actions on the authoritative enrollment."""

import hashlib
from datetime import timedelta

from odoo import api, fields, models
from odoo.exceptions import AccessError, LockError, ValidationError
from odoo.tools.binary import BinaryBytes

COORDINATOR = "training_management.group_training_coordinator"


class PracticeAction(models.Model):
    _name = "training.practice.action"
    _description = "Post-training Practice Action"
    _check_company_auto = True
    _order = "due_date, id"

    name = fields.Char(required=True)
    enrollment_id = fields.Many2one("training.enrollment", required=True, ondelete="restrict", check_company=True)
    delivery_id = fields.Many2one(related="enrollment_id.delivery_id", store=True)
    company_id = fields.Many2one(related="enrollment_id.company_id", store=True)
    completed_on = fields.Date(required=True, string="Training Completed On")
    horizon = fields.Selection([("30", "30 Days"), ("60", "60 Days")], default="30", required=True)
    due_date = fields.Date(compute="_compute_due_date", store=True)
    access_withdrawn = fields.Boolean(readonly=True, copy=False)
    trainer_feedback = fields.Boolean(string="Trainer Feedback Included")
    service_reference = fields.Char(required=True, string="Agreed Service Reference")
    retention_id = fields.Many2one(
        "training.retention.category", required=True, ondelete="restrict", check_company=True
    )
    reminder_days = fields.Integer(default=7, help="Zero disables reminders. First reminder on the due date.")
    state = fields.Selection(
        [("planned", "Planned"), ("done", "Done"), ("closed", "Closed")],
        default="planned",
        readonly=True,
        required=True,
    )
    entry_ids = fields.One2many("training.practice.entry", "action_id", readonly=True)

    @api.depends("completed_on", "horizon")
    def _compute_due_date(self):
        for action in self:
            action.due_date = (
                action.completed_on + timedelta(days=int(action.horizon)) if action.completed_on else False
            )

    @api.private
    def _coordinator(self):
        self.check_access("write" if self else "create")
        if not self.env.user.active or not self.env.user.has_group(COORDINATOR):
            raise AccessError(self.env._("Only a training coordinator may manage practice plans."))

    @api.constrains("enrollment_id", "completed_on", "retention_id", "reminder_days", "service_reference")
    def _check_plan(self):
        for action in self:
            if (
                action.enrollment_id.state != "confirmed"
                or action.delivery_id.state not in ("delivered", "closed")
                or not action.retention_id.approved_at
                or not action.enrollment_id.commercially_authorized
                or action.enrollment_id.access_state in ("suspended", "revoked")
                or action.reminder_days < 0
                or action.completed_on > fields.Date.context_today(action.with_context(tz=action.delivery_id.timezone))
                or not action.service_reference.strip()
            ):
                raise ValidationError(
                    self.env._(
                        "Use a completed training, a confirmed enrollment, an approved retention policy and a non-negative reminder interval."
                    )
                )

    @api.model_create_multi
    def create(self, vals_list):
        self._coordinator()
        clean = {k: v for k, v in self.env.context.items() if not k.startswith("default_")}
        values = [self._add_missing_default_values(dict(v)) for v in vals_list]
        if any(
            set(v)
            - {
                "name",
                "enrollment_id",
                "completed_on",
                "horizon",
                "trainer_feedback",
                "service_reference",
                "retention_id",
                "reminder_days",
                "state",
            }
            or v.get("state", "planned") != "planned"
            for v in values
        ):
            raise ValidationError(self.env._("Create a planned action; its history is generated by the server."))
        enrollments = self.env["training.enrollment"].browse([v["enrollment_id"] for v in values])
        enrollments.check_access("read")
        enrollments.delivery_id._serialize()
        return super(PracticeAction, self.with_context(clean)).create(values)  # pylint: disable=context-overridden

    def write(self, vals):  # pylint: disable=method-required-super  # immutable definition; controlled operations below
        raise ValidationError(self.env._("Keep the agreed action unchanged; close it and create a replacement."))

    @api.ondelete(at_uninstall=False)
    def _keep_plan(self):
        raise ValidationError(self.env._("Keep practice actions and their history."))

    def copy_data(self, default=None):  # pylint: disable=method-required-super
        raise ValidationError(self.env._("Create a new agreed action instead of copying its history."))

    def action_close(self):
        self._coordinator()
        for action in self:
            action._lock()
            if action.state != "closed":
                action._append("closed", self.env._("Closed by coordination"))
                action._set_state("closed")
        return True

    def action_withdraw_access(self):
        self._coordinator()
        for action in self:
            action._lock()
            if not action.access_withdrawn:
                action._append("withdrawn", self.env._("Practice access withdrawn by coordination"))
                super(PracticeAction, action).write({"access_withdrawn": True})  # pylint: disable=super-method-mismatch  # checked irreversible withdrawal
        return True

    @api.private
    def _lock(self):
        # Same delivery fence as enrollment lifecycle, then this action. The
        # MVCC fence makes concurrent submissions retry on a fresh snapshot.
        self.ensure_one()
        self.delivery_id._serialize()
        self.lock_for_update()
        self.env.cr.execute("UPDATE training_practice_action SET write_date = write_date WHERE id = %s", [self.id])
        self.invalidate_recordset()

    @api.private
    def _set_state(self, state):
        return super().write({"state": state})  # pylint: disable=super-method-mismatch  # checked private state transition

    @api.private
    def _eligible(self, role):
        self.ensure_one()
        user = self.env.user
        e = self.sudo().enrollment_id
        if (
            not user.active
            or user._is_public()
            or e.company_id not in user.company_ids
            or not e.commercially_authorized
            or e.prerequisites == "pending"
            or self.sudo().access_withdrawn
            or e.state not in ("confirmed", "closed")
            or e.access_state == "suspended"
            or (e.access_state == "revoked" and e.state != "closed")
            or e.delivery_id.state not in ("delivered", "closed")
        ):
            return False
        if role == "participant":
            return e.user_id == user and e.participant_id == user.partner_id
        return bool(
            role == "trainer"
            and self.sudo().trainer_feedback
            and (e.learning_tutor_id or e.delivery_id.learning_tutor_id) == user
        )

    @api.private
    def _append(self, kind, body, data=b"", filename=""):
        filename = filename.replace("\\", "/").split("/")[-1] if data else ""
        if data and (not filename or len(data) > 20 * 1024 * 1024):
            raise ValidationError(self.env._("Select a named file of at most 20 MB."))
        entry = self.env["training.practice.entry"]._create_evidence(
            {
                "action_id": self.id,
                "kind": kind,
                "body": body,
                "data": BinaryBytes(data) if data else False,
                "filename": filename,
                "sha256": hashlib.sha256(data).hexdigest() if data else False,
            }
        )
        entry.invalidate_recordset(["data"])
        entry._store_evidence({"sealed_at": fields.Datetime.now()})
        return entry

    @api.private
    def _submit(self, role, body="", data=b"", filename=""):
        if not self._eligible(role):
            raise AccessError(self.env._("This private practice action is unavailable."))
        self.sudo()._lock()
        if not self._eligible(role):
            raise AccessError(self.env._("This private practice action is unavailable."))
        if self.state == "closed":
            raise ValidationError(self.env._("This action is closed."))
        kind = "done" if role == "participant" else "feedback"
        if role == "participant" and self.state == "done":
            return False  # A double click never appends another completion.
        if role == "trainer" and (self.state != "done" or not body.strip()):
            raise ValidationError(self.env._("Complete the action before recording a trainer comment."))
        # Repeated identical feedback is idempotent; later comments append history.
        previous = self.sudo().entry_ids.filtered(lambda e: e.kind == kind)
        if (
            previous
            and previous[-1].body == body.strip()
            and previous[-1].sha256 == (hashlib.sha256(data).hexdigest() if data else False)
            and previous[-1].filename == (filename.replace("\\", "/").split("/")[-1] if data else False)
        ):
            return False
        self._append(kind, body.strip(), data, filename)
        if role == "participant":
            self.sudo()._set_state("done")
        return True

    @api.private
    def _portal_actions(self):
        user = self.env.user
        if not user.active or user._is_public():
            return self.browse()
        candidates = self.sudo().search(
            [
                ("company_id", "in", user.company_ids.ids),
                "|",
                ("enrollment_id.user_id", "=", user.id),
                "|",
                ("enrollment_id.learning_tutor_id", "=", user.id),
                ("delivery_id.learning_tutor_id", "=", user.id),
            ]
        )
        return candidates.filtered(
            lambda action: (
                action.with_user(user)._eligible("participant") or action.with_user(user)._eligible("trainer")
            )
        )

    @api.private
    def _portal_rows(self):
        user = self.env.user
        rows = []
        for action in self._portal_actions():
            participant = action.with_user(user)._eligible("participant")
            if not participant and not action.with_user(user)._eligible("trainer"):
                continue
            rows.append(
                {
                    "id": action.id,
                    "name": action.name,
                    "training": action.delivery_id.name,
                    "participant": action.enrollment_id.participant_id.name,
                    "due": action.due_date,
                    "state": action.state,
                    "state_label": dict(action._fields["state"]._description_selection(self.env))[action.state],
                    "role": "participant" if participant else "trainer",
                    "entries": [
                        {
                            "id": e.id,
                            "body": e.body,
                            "filename": e.filename,
                            "kind": dict(e._fields["kind"]._description_selection(self.env))[e.kind],
                            "author": e.create_uid.name,
                            "date": e.create_date,
                        }
                        for e in action.entry_ids
                    ],
                }
            )
        return rows

    @api.model
    def _cron_reminders(self):
        for action in self.sudo().search(
            [("state", "=", "planned"), ("access_withdrawn", "=", False), ("reminder_days", ">", 0)]
        ):
            try:
                with self.env.cr.savepoint():
                    action._lock()
                    today = fields.Date.context_today(action.with_context(tz=action.delivery_id.timezone))
                    if action.state == "planned" and today >= action.due_date:
                        window = (today - action.due_date).days // action.reminder_days
                        self.env["training.practice.notice"]._queue_action(action, window)
            except LockError:
                # A concurrent participant operation wins; the next scheduler
                # run rechecks this action without starving other deliveries.
                continue


class PracticeEntry(models.Model):
    _name = "training.practice.entry"
    _inherit = "training.learning.evidence"
    _description = "Private Practice Evidence and Feedback"
    _order = "id"
    _rec_name = "kind"

    action_id = fields.Many2one("training.practice.action", required=True, ondelete="restrict")
    company_id = fields.Many2one(related="action_id.company_id", store=True)
    kind = fields.Selection(
        [("done", "Done"), ("feedback", "Trainer Feedback"), ("closed", "Closed"), ("withdrawn", "Access Withdrawn")],
        required=True,
    )
    body = fields.Text()
    data = fields.Binary(attachment=True, readonly=True)
    filename = fields.Char()
    sha256 = fields.Char()
    sealed_at = fields.Datetime()

    def _can_return_content(self, field_name=None, access_token=None):
        self.env["training.document.policy"]._check_read(self)
        return field_name == "data"


class PracticeDocumentPolicy(models.AbstractModel):
    _inherit = "training.document.policy"  # pylint: disable=consider-merging-classes-inherited  # P11 proof access is separate from closure documents

    @api.private
    def _document(self, record):
        target = record.sudo()
        if (
            target._name in ("ir.attachment", "mail.message")
            and (target.res_model if target._name == "ir.attachment" else target.model) == "training.practice.entry"
        ):
            target = self.env["training.practice.entry"].sudo().browse(target.res_id).exists()
            if not target:
                raise AccessError(self.env._("This private practice action is unavailable."))
        return target if target._name == "training.practice.entry" else super()._document(record)

    @api.private
    def _is_pedagogical(self, document):
        return bool(document and document._name == "training.practice.entry") or super()._is_pedagogical(document)

    @api.private
    def _can_read(self, record):
        document = self._document(record)
        if document._name == "training.practice.entry":
            action = document.action_id.with_user(self.env.user)
            return (
                action._eligible("participant")
                or action._eligible("trainer")
                or (
                    self.env.user.active
                    and self.env.user.has_group(COORDINATOR)
                    and document.with_env(self.env(su=False)).has_access("read")
                )
            )
        return super()._can_read(record)

    @api.private
    def _check_send(self, document, partners, **kwargs):
        if document and document._name == "training.practice.entry":
            raise ValidationError(
                self.env._("Private practice evidence is available through the authenticated portal only.")
            )
        return super()._check_send(document, partners, **kwargs)


class PracticeEnrollment(models.Model):
    _inherit = "training.enrollment"  # pylint: disable=consider-merging-classes-inherited  # P11 revocation policy stays separate from material access

    @api.private
    def _store(self, values, reason=False):
        # Ordinary delivery closure revokes support access. Explicit revocation
        # or cancellation also withdraws P11, permanently, with its own trace.
        previous_access = self.access_state
        result = super()._store(values, reason)
        if values.get("access_state") == "revoked" and (
            values.get("state") != "closed" or previous_access in ("suspended", "revoked")
        ):
            actions = (
                self.env["training.practice.action"]
                .sudo()
                .search([("enrollment_id", "in", self.ids), ("access_withdrawn", "=", False)])
            )
            for action in actions:
                action._append("withdrawn", self.env._("Practice access withdrawn with enrollment access"))
                super(PracticeAction, action).write({"access_withdrawn": True})  # pylint: disable=super-method-mismatch  # checked lifecycle withdrawal
        return result
