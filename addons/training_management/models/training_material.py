"""Private PDF versions and stable delivery references; bytes stay in Odoo attachments."""

import hashlib

from odoo import api, fields, models
from odoo.exceptions import AccessError, UserError, ValidationError

COORDINATOR = "training_management.group_training_coordinator"


class TrainingMaterial(models.Model):
    _name = "training.material"
    _description = "Private Training PDF"
    _order = "name, id desc"
    _check_company_auto = True

    name = fields.Char(required=True)
    version = fields.Char(required=True, default="1")
    program_id = fields.Many2one("training.program.version", required=True, ondelete="restrict", check_company=True)
    company_id = fields.Many2one(related="program_id.company_id", store=True, index=True)
    delivery_id = fields.Many2one("training.delivery", ondelete="restrict", check_company=True, string="Group Only")
    previous_id = fields.Many2one(
        "training.material", readonly=True, copy=False, ondelete="restrict", check_company=True
    )
    data = fields.Binary(required=True, attachment=True, copy=False, string="PDF File")
    filename = fields.Char(required=True)
    sha256 = fields.Char(readonly=True, copy=False)
    frozen_at = fields.Datetime(readonly=True, copy=False, string="Version Frozen On")
    frozen_by_id = fields.Many2one("res.users", readonly=True, copy=False, ondelete="restrict")
    withdrawn = fields.Boolean(readonly=True, copy=False)
    assignment_ids = fields.One2many("training.material.assignment", "material_id", readonly=True, copy=False)
    revision = fields.Integer(readonly=True, default=0, copy=False)

    _one_successor = models.Constraint("UNIQUE(previous_id)", "A replacement version already exists.")

    @api.private
    def _require_coordinator(self):
        self.check_access("write" if self else "create")
        if not self.env.su and not self.env.user.has_group(COORDINATOR):
            raise AccessError(self.env._("Only the training coordinator may manage private PDFs."))

    @api.private
    def _serialize(self):  # pylint: disable=missing-return  # internal write fence, no return value
        self.sorted("id").lock_for_update()
        self.invalidate_recordset()
        # A write fence also rejects stale REPEATABLE READ snapshots.
        for material in self:
            super(TrainingMaterial, material).write({"revision": material.revision + 1})  # pylint: disable=super-method-mismatch  # private fence bypasses immutable public write

    @api.private
    def _fingerprint(self):
        self.ensure_one()
        raw = self.data.content if self.data else b""
        if not raw.startswith(b"%PDF-"):
            raise ValidationError(self.env._("Upload a PDF file."))
        return hashlib.sha256(raw).hexdigest()

    @api.constrains("program_id", "delivery_id", "previous_id")
    def _check_scope(self):
        for material in self:
            if material.delivery_id and material.delivery_id.program_id != material.program_id:
                raise ValidationError(self.env._("The support and its delivery must use the same programme."))
            if material.previous_id and (
                material.previous_id.program_id != material.program_id
                or material.previous_id.delivery_id != material.delivery_id
            ):
                raise ValidationError(self.env._("A new PDF version keeps its programme and group."))

    @api.model_create_multi
    def create(self, vals_list):
        self._require_coordinator()
        prepared = []
        for vals in vals_list:
            vals = self._add_missing_default_values(dict(vals))
            if any(
                vals.get(key)
                for key in ("sha256", "frozen_at", "frozen_by_id", "withdrawn", "revision", "assignment_ids")
            ):
                raise ValidationError(self.env._("PDF evidence is generated by the server."))
            vals.update(
                sha256=False, frozen_at=False, frozen_by_id=False, withdrawn=False, revision=0, assignment_ids=[]
            )
            if vals.get("previous_id"):
                previous = self.browse(vals["previous_id"])
                previous._require_coordinator()
                previous._serialize()
            prepared.append(vals)
        with self.env.cr.savepoint():
            records = super().create(prepared)
            for material in records:
                super(TrainingMaterial, material).write({"sha256": material._fingerprint()})  # pylint: disable=super-method-mismatch  # server-derived evidence after file validation
                if material.delivery_id:
                    self.env["training.material.assignment"].create(
                        {"material_id": material.id, "delivery_id": material.delivery_id.id}
                    )
            return records

    def write(self, vals):
        self._require_coordinator()
        with self.env.cr.savepoint():
            self._serialize()
            if set(vals) - {"name", "version", "data", "filename"} or any(
                item.frozen_at or item.withdrawn for item in self
            ):
                raise ValidationError(self.env._("Keep this PDF version; create a new version to correct it."))
            result = super().write(vals)
            for material in self:
                super(TrainingMaterial, material).write({"sha256": material._fingerprint()})
            return result

    @api.private
    def _freeze(self):  # pylint: disable=missing-return  # private first-diffusion evidence, no return value
        for material in self.filtered(lambda item: not item.frozen_at):
            material._serialize()
            if not material.frozen_at:
                super(TrainingMaterial, material).write(  # pylint: disable=super-method-mismatch  # controlled first-diffusion evidence
                    {
                        "frozen_at": fields.Datetime.now(),
                        "frozen_by_id": self.env.uid,
                        "sha256": material._fingerprint(),
                    }
                )

    def action_withdraw(self):
        self._require_coordinator()
        self._serialize()
        return super().write({"withdrawn": True})  # pylint: disable=super-method-mismatch  # checked withdrawal preserves the record

    def action_new_version(self):
        self.ensure_one()
        self._require_coordinator()
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("New PDF Version"),
            "res_model": self._name,
            "view_mode": "form",
            "target": "current",
            "context": {
                "default_name": self.name,
                "default_version": False,
                "default_program_id": self.program_id.id,
                "default_delivery_id": self.delivery_id.id,
                "default_previous_id": self.id,
            },
        }

    def export_data(self, fields_to_export):
        self.check_access("read")
        return super().export_data(fields_to_export)

    def _export_rows(self, fields, *, _is_toplevel_call=True):  # pylint: disable=method-required-super  # native recursion must enforce the same export restriction
        self.check_access("read")
        raise UserError(
            self.env._("Bulk export of private support records is unavailable. Download an authorized PDF instead.")
        )

    def copy_data(self, default=None):  # pylint: disable=method-required-super  # version creation must not clone evidence or bytes
        raise ValidationError(self.env._("Use New PDF Version to preserve the original file."))

    @api.ondelete(at_uninstall=False)
    def _unlink_keep_evidence(self):
        raise ValidationError(self.env._("Withdraw private PDFs instead of deleting their history."))

    def _can_return_content(self, field_name=None, access_token=None):
        self.env["training.document.policy"]._check_read(self)
        return field_name == "data"


class TrainingMaterialAssignment(models.Model):
    _name = "training.material.assignment"
    _description = "Delivery PDF Reference"
    _order = "sequence, id"
    _check_company_auto = True
    _rec_name = "material_id"

    delivery_id = fields.Many2one(
        "training.delivery", required=True, ondelete="restrict", check_company=True, index=True
    )
    company_id = fields.Many2one(related="delivery_id.company_id", store=True)
    material_id = fields.Many2one("training.material", required=True, ondelete="restrict", check_company=True)
    sequence = fields.Integer(default=10)
    withdrawn = fields.Boolean(readonly=True, copy=False)
    _unique_reference = models.Constraint(
        "UNIQUE(delivery_id, material_id)", "This PDF is already assigned to the delivery."
    )

    @api.constrains("delivery_id", "material_id")
    def _check_scope(self):
        for assignment in self:
            material = assignment.material_id
            if material.program_id != assignment.delivery_id.program_id or (
                material.delivery_id and material.delivery_id != assignment.delivery_id
            ):
                raise ValidationError(self.env._("Choose a PDF for this exact programme and group."))

    @api.model_create_multi
    def create(self, vals_list):
        prepared = []
        for vals in vals_list:
            vals = self._add_missing_default_values(dict(vals))
            if vals.get("withdrawn"):
                raise ValidationError(self.env._("Create an active PDF reference."))
            vals["withdrawn"] = False
            self.env["training.delivery"].browse(vals.get("delivery_id"))._serialize()
            material = self.env["training.material"].browse(vals.get("material_id"))
            material._require_coordinator()
            material._serialize()
            if material.withdrawn:
                raise ValidationError(self.env._("This PDF has been withdrawn."))
            self.env["training.delivery"].browse(vals.get("delivery_id"))._require_coordinator()
            prepared.append(vals)
        records = super().create(prepared)
        for assignment in records:
            assignment._freeze_if_available()
        return records

    @api.private
    def _freeze_if_available(self):
        # Freeze at publication, including a scheduled opening: time alone can
        # activate S03 access later, without another write or a cron execution.
        for assignment in self.filtered(lambda item: not item.withdrawn):
            if any(e._effective_state() in ("active", "scheduled") for e in assignment.delivery_id.enrollment_ids) or (
                assignment.delivery_id.state in ("confirmed", "ongoing")
                and any(not s.cancelled for s in assignment.delivery_id.session_ids)
            ):
                assignment.material_id._freeze()

    def write(self, vals):
        self.mapped("delivery_id")._require_coordinator()
        if set(vals) - {"sequence"}:
            raise ValidationError(self.env._("Keep the assigned version; withdraw it and add its replacement."))
        return super().write(vals)

    def action_withdraw(self):
        self.mapped("delivery_id")._require_coordinator()
        return super().write({"withdrawn": True})  # pylint: disable=super-method-mismatch  # checked withdrawal preserves the record

    def _export_rows(self, fields, *, _is_toplevel_call=True):  # pylint: disable=method-required-super  # includes nested native exports from deliveries
        self.check_access("read")
        raise UserError(
            self.env._("Bulk export of private support records is unavailable. Download an authorized PDF instead.")
        )

    @api.ondelete(at_uninstall=False)
    def _unlink_keep_reference(self):
        raise ValidationError(self.env._("Withdraw this reference instead of deleting its history."))


class TrainingProgram(models.Model):
    _inherit = "training.program.version"

    material_ids = fields.One2many(
        "training.material", "program_id", domain=[("delivery_id", "=", False)], copy=False, groups=COORDINATOR
    )

    def action_add_material(self):
        self.ensure_one()
        self._require_pdf_coordinator()
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("Add Private PDF"),
            "res_model": "training.material",
            "view_mode": "form",
            "context": {"default_program_id": self.id},
        }


class TrainingDelivery(models.Model):
    _inherit = "training.delivery"  # pylint: disable=consider-merging-classes-inherited  # Private materials and evaluations have separate lifecycles.

    material_assignment_ids = fields.One2many(
        "training.material.assignment", "delivery_id", copy=False, groups=COORDINATOR
    )

    @api.model_create_multi
    def create(self, vals_list):
        records = super().create(vals_list)
        records.action_add_programme_materials()
        return records

    def action_add_programme_materials(self):
        self._require_coordinator()
        for delivery in self:
            materials = self.env["training.material"].search(
                [("program_id", "=", delivery.program_id.id), ("delivery_id", "=", False)]
            )
            latest = (materials - materials.mapped("previous_id")).filtered(lambda item: not item.withdrawn)
            if latest - delivery.material_assignment_ids.material_id:
                delivery._serialize()
            for material in latest - delivery.material_assignment_ids.material_id:
                self.env["training.material.assignment"].create(
                    {"delivery_id": delivery.id, "material_id": material.id}
                )
        return True

    def action_add_material(self):
        self.ensure_one()
        self._require_coordinator()
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("Add Group PDF"),
            "res_model": "training.material",
            "view_mode": "form",
            "context": {"default_program_id": self.program_id.id, "default_delivery_id": self.id},
        }

    def action_assign_material(self):
        self.ensure_one()
        self._require_coordinator()
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("Assign PDF Version"),
            "res_model": "training.material.assignment",
            "view_mode": "form",
            "target": "new",
            "context": {"default_delivery_id": self.id},
        }

    def _transition(self, target, reason=None, conflict_reason=None):
        result = super()._transition(target, reason, conflict_reason)
        self.material_assignment_ids._freeze_if_available()
        return result

    def write(self, vals):
        if set(vals) & {"program_id", "company_id"} and any(item.material_assignment_ids for item in self):
            raise ValidationError(self.env._("A delivery with PDF references keeps its programme and company."))
        return super().write(vals)


class TrainingEnrollment(models.Model):
    _inherit = "training.enrollment"

    def _store(self, values, reason=False):
        result = super()._store(values, reason)
        if self._effective_state() in ("active", "scheduled"):
            self.delivery_id.material_assignment_ids._freeze_if_available()
        return result


class TrainingSession(models.Model):
    _inherit = "training.session"

    def _create_scheduled(self, vals_list, reason=None, conflict_reason=None):
        records = super()._create_scheduled(vals_list, reason=reason, conflict_reason=conflict_reason)
        records.delivery_id.material_assignment_ids._freeze_if_available()
        return records
