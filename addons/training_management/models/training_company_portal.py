"""Explicit client scope projected through the existing Odoo portal identity."""

import hashlib

from odoo import api, fields, models
from odoo.exceptions import AccessError, ConcurrencyError, LockError, ValidationError
from odoo.tools import email_normalize

COORDINATOR = "training_management.group_training_coordinator"


class TrainingCompanyAuthorization(models.Model):
    _name = "training.company.authorization"
    _description = "Training Company Portal Authorization"
    _check_company_auto = True
    _rec_name = "customer_id"

    company_id = fields.Many2one(
        "res.company", required=True, default=lambda self: self.env.company, ondelete="restrict"
    )
    customer_id = fields.Many2one("res.partner", required=True, check_company=True, ondelete="restrict")
    user_id = fields.Many2one("res.users", required=True, ondelete="restrict")
    allocation_ids = fields.Many2many("training.seat.allocation", check_company=True)
    state = fields.Selection(
        [("draft", "Draft"), ("active", "Active"), ("revoked", "Revoked")],
        default="draft",
        required=True,
        readonly=True,
        copy=False,
    )
    confirmed_by_id = fields.Many2one("res.users", readonly=True, copy=False, ondelete="restrict")
    confirmed_at = fields.Datetime(readonly=True, copy=False)
    revoked_by_id = fields.Many2one("res.users", readonly=True, copy=False, ondelete="restrict")
    revoked_at = fields.Datetime(readonly=True, copy=False)

    @api.private
    def _require_coordinator(self):
        self.check_access("write" if self else "create")
        if not self.env.su and not self.env.user.has_group(COORDINATOR):
            raise AccessError(self.env._("Only the training coordinator may manage company portal authorizations."))

    @api.constrains("customer_id", "user_id", "allocation_ids", "company_id")
    def _check_scope(self):
        for grant in self:
            if (
                grant.customer_id.commercial_partner_id != grant.customer_id
                or not grant.user_id.active
                or not grant.user_id.has_group("base.group_portal")
                or grant.company_id not in grant.user_id.company_ids
                or any(
                    a.customer_id.commercial_partner_id != grant.customer_id or a.company_id != grant.company_id
                    for a in grant.allocation_ids
                )
            ):
                raise ValidationError(
                    self.env._("Choose an active portal user and allocations for the same client company and operator.")
                )

    @api.model_create_multi
    def create(self, vals_list):
        self._require_coordinator()
        values = [self._add_missing_default_values(dict(v)) for v in vals_list]
        allowed = {"company_id", "customer_id", "user_id", "allocation_ids", "state"}
        if any(set(v) - allowed or v.get("state", "draft") != "draft" for v in values):
            raise ValidationError(
                self.env._("Create a draft authorization; confirmation evidence is generated by the server.")
            )
        return super().create(values)

    def write(self, vals):
        self._require_coordinator()
        self.lock_for_update()
        self.invalidate_recordset()
        if any(g.state != "draft" for g in self) or set(vals) - {
            "company_id",
            "customer_id",
            "user_id",
            "allocation_ids",
        }:
            raise ValidationError(
                self.env._("Confirmed authorizations are immutable. Revoke and replace the authorization.")
            )
        return super().write(vals)

    def action_confirm(self):
        # pylint: disable=super-method-mismatch  # controlled state and server-authored evidence
        self._require_coordinator()
        self.lock_for_update()
        self.invalidate_recordset()
        self._check_scope()
        if any(g.state == "revoked" for g in self):
            raise ValidationError(self.env._("A revoked authorization cannot be reactivated."))
        return super(TrainingCompanyAuthorization, self.filtered(lambda g: g.state == "draft")).write(
            {"state": "active", "confirmed_by_id": self.env.uid, "confirmed_at": fields.Datetime.now()}
        )

    def action_revoke(self):
        # pylint: disable=super-method-mismatch  # controlled state and server-authored evidence
        self._require_coordinator()
        self.lock_for_update()
        self.invalidate_recordset()
        return super(TrainingCompanyAuthorization, self.filtered(lambda g: g.state == "active")).write(
            {"state": "revoked", "revoked_by_id": self.env.uid, "revoked_at": fields.Datetime.now()}
        )

    @api.ondelete(at_uninstall=False)
    def _unlink_except_confirmed(self):
        if any(g.state != "draft" for g in self):
            raise ValidationError(self.env._("Keep the authorization and revocation evidence."))


class TrainingCompanyNomination(models.Model):
    _name = "training.company.nomination"
    _description = "Client Participant Nomination"
    _check_company_auto = True

    allocation_id = fields.Many2one("training.seat.allocation", required=True, ondelete="restrict", check_company=True)
    company_id = fields.Many2one(related="allocation_id.company_id", store=True)
    name = fields.Char(required=True)
    email = fields.Char()
    submitted_by_id = fields.Many2one("res.users", required=True, ondelete="restrict")
    fingerprint = fields.Char(required=True, readonly=True)
    enrollment_id = fields.Many2one("training.enrollment", check_company=True, ondelete="restrict")
    state = fields.Selection(
        [("proposed", "Proposed"), ("processed", "Processed"), ("rejected", "Rejected")],
        default="proposed",
        required=True,
    )
    _unique_nomination = models.Constraint(
        "UNIQUE(allocation_id, fingerprint)", "This nomination already exists for the allocation."
    )

    @api.constrains("enrollment_id", "allocation_id", "state")
    def _check_enrollment(self):
        for row in self:
            if (row.enrollment_id and row.enrollment_id.allocation_id != row.allocation_id) or (
                row.state == "processed" and not row.enrollment_id
            ):
                raise ValidationError(
                    self.env._(
                        "Select the manually created enrollment of this allocation before marking the nomination processed."
                    )
                )


class TrainingCompanyDocument(models.Model):
    _name = "training.company.document"
    _description = "Authorized Client Training PDF"
    _check_company_auto = True

    name = fields.Char(required=True)
    allocation_id = fields.Many2one("training.seat.allocation", required=True, ondelete="restrict", check_company=True)
    company_id = fields.Many2one(related="allocation_id.company_id", store=True)
    data = fields.Binary(required=True, attachment=False)
    filename = fields.Char(required=True)
    released = fields.Boolean(default=False, copy=False)
    frozen_at = fields.Datetime(readonly=True, copy=False)

    @api.constrains("data", "filename")
    def _check_pdf(self):
        for row in self:
            if not row.data or not row.data.content.startswith(b"%PDF-") or not row.filename.lower().endswith(".pdf"):
                raise ValidationError(self.env._("Upload an authorized client PDF."))

    @api.model_create_multi
    def create(self, vals_list):
        vals_list = [self._add_missing_default_values(dict(v)) for v in vals_list]
        if any(v.get("frozen_at") for v in vals_list):
            raise ValidationError(self.env._("Client document evidence is generated by the server."))
        return super().create(
            [dict(v, frozen_at=fields.Datetime.now() if v.get("released") else False) for v in vals_list]
        )

    def write(self, vals):
        self.check_access("write")
        self.lock_for_update()
        self.invalidate_recordset()
        if "frozen_at" in vals or (any(r.frozen_at for r in self) and set(vals) - {"released"}):
            raise ValidationError(
                self.env._("A released client PDF is immutable. Withdraw it and create another document.")
            )
        for row in self:
            values = dict(vals)
            if values.get("released") and not row.frozen_at:
                values["frozen_at"] = fields.Datetime.now()
            super(TrainingCompanyDocument, row).write(values)
        return True

    @api.ondelete(at_uninstall=False)
    def _unlink_except_released(self):
        if any(r.frozen_at for r in self):
            raise ValidationError(self.env._("Keep released client documents; withdraw their portal access instead."))


class TrainingCompanyService(models.AbstractModel):
    _name = "training.company.service"
    _description = "Training Company Portal Projection"

    @api.private
    def _grants(self):
        user = self.env.user
        if not user.active or not user.has_group("base.group_portal"):
            return self.env["training.company.authorization"]
        return (
            self.env["training.company.authorization"]
            .sudo()
            .search([("user_id", "=", user.id), ("state", "=", "active"), ("company_id", "in", user.company_ids.ids)])
        )

    @api.private
    def _allocation(self, allocation_id):
        grants = self._grants()
        allocation = grants.allocation_ids.filtered(lambda a: a.id == allocation_id)
        if (
            not allocation
            or allocation.company_id not in self.env.user.company_ids
            or not any(
                g.company_id == allocation.company_id
                and g.customer_id == allocation.customer_id.commercial_partner_id
                and allocation in g.allocation_ids
                for g in grants
            )
        ):
            raise AccessError(self.env._("This company training dossier is not authorized."))
        return allocation

    @api.private
    def _rows(self):
        rows = []
        for allocation in self._grants().allocation_ids:
            try:
                allocation = self._allocation(allocation.id)
            except AccessError:
                continue
            rows.append(
                {
                    "id": allocation.id,
                    "name": allocation.delivery_id.name,
                    "customer": allocation.customer_id.commercial_partner_id.name,
                    "state": dict(allocation._fields["state"]._description_selection(self.env))[allocation.state],
                }
            )
        return rows

    @api.private
    def _nominate(self, allocation_id, name, email):
        allocation = self._allocation(allocation_id)
        # Serialize the existing allocation using native row locking. The write
        # fence below ensures concurrent nominations retry on a fresh snapshot.
        try:
            allocation.delivery_id._serialize()
        except LockError as error:
            raise ConcurrencyError("Concurrent client nomination; retry with a fresh snapshot") from error
        allocation.invalidate_recordset()
        if not allocation._available() or allocation.delivery_id.state in ("cancelled", "closed", "delivered"):
            raise ValidationError(self.env._("This dossier no longer accepts nominations."))
        name, email = (name or "").strip(), (email or "").strip()
        normalized = email_normalize(email) if email else ""
        if not name or len(name) > 200 or len(email) > 254 or (email and not normalized):
            raise ValidationError(self.env._("Enter a participant name and, if supplied, a valid email address."))
        fingerprint = hashlib.sha256((name.casefold() + "\n" + normalized).encode()).hexdigest()
        nominations = self.env["training.company.nomination"].sudo()
        existing = nominations.search(
            [("allocation_id", "=", allocation.id), ("fingerprint", "=", fingerprint)], limit=1
        )
        return existing or nominations.create(
            {
                "allocation_id": allocation.id,
                "name": name,
                "email": normalized,
                "submitted_by_id": self.env.uid,
                "fingerprint": fingerprint,
            }
        )

    @api.private
    def _request_rows(self):
        # Optional Sales integration supplies CRM projections, never raw records.
        return []


class TrainingCompanyDocumentPolicy(models.AbstractModel):
    _inherit = "training.document.policy"  # pylint: disable=consider-merging-classes-inherited  # client documents have their own exact allocation grant

    @api.private
    def _document(self, record):
        target = record.sudo()
        if (
            target._name == "ir.attachment"
            and target.res_model in ("training.company.document", "training.intra.version")
            and target.res_id
        ):
            return self.env[target.res_model].sudo().browse(target.res_id).exists()
        if target._name in ("training.company.document", "training.intra.version"):
            return target
        return super()._document(record)

    @api.private
    def _is_pedagogical(self, document):
        return bool(
            document and document._name in ("training.company.document", "training.intra.version")
        ) or super()._is_pedagogical(document)

    @api.private
    def _can_read(self, record):
        document = self._document(record)
        if document and document._name in ("training.company.document", "training.intra.version"):
            # Public/native binary tokens never substitute for internal ACLs.
            # Portal files are served solely by the exact-grant controller.
            return not self.env.user.share and document.with_env(self.env(su=False)).has_access("read")
        return super()._can_read(record)

    @api.private
    def _check_send(self, document, partners, **kwargs):
        if document and document._name in ("training.company.document", "training.intra.version"):
            raise AccessError(self.env._("Client dossier PDFs are distributed through the authorized portal only."))
        return super()._check_send(document, partners, **kwargs)
