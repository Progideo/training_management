from odoo import api, fields, models
from odoo.exceptions import ValidationError


class SaleOrderLine(models.Model):
    _inherit = "sale.order.line"

    training_program_id = fields.Many2one(
        "training.program.version",
        string="Programme Version",
        ondelete="restrict",
        check_company=True,
        copy=True,
        domain="[('state', 'in', ('validated', 'published')), ('company_id', '=', company_id)]",
    )
    training_program_label = fields.Char(
        string="Programme Reference on Quotation",
        readonly=True,
        copy=True,
        help="The course and version label kept as it appeared when the quotation line was prepared.",
    )

    @api.constrains("training_program_id", "product_id", "order_id")
    def _check_training_program(self):
        for line in self:
            course = line.product_id.product_tmpl_id.training_course_id
            program = line.training_program_id
            if bool(course) != bool(program):
                raise ValidationError(self.env._("A training product and programme version must be selected together."))
            if program and (program.course_id != course or program.company_id != line.company_id):
                raise ValidationError(self.env._("The programme must match the commercial product and company."))
            if program and line.state in ("draft", "sent") and program.state not in ("validated", "published"):
                raise ValidationError(self.env._("Only validated or published programmes may be quoted."))

    def write(self, vals):
        if "training_program_label" in vals:
            raise ValidationError(self.env._("The quoted programme reference is generated by the system."))
        if "training_program_id" in vals and any(line.state == "sale" for line in self):
            raise ValidationError(self.env._("The programme version on a confirmed order is fixed."))
        result = super().write(vals)
        if "training_program_id" in vals:
            self._store_training_program_labels()
        return result

    @api.model_create_multi
    def create(self, vals_list):
        vals_list = [
            {key: value for key, value in vals.items() if key != "training_program_label"} for vals in vals_list
        ]
        lines = super().create(vals_list)
        lines._store_training_program_labels()
        return lines

    def _store_training_program_labels(self):  # pylint: disable=missing-return  # compute method, nothing to return
        for line in self:
            if not line.training_program_id and not line.training_program_label:
                continue
            label = line.training_program_id.display_name if line.training_program_id else False
            super(SaleOrderLine, line).write({"training_program_label": label})  # pylint: disable=super-method-mismatch  # deliberate bypass of the controlled write, see _store

    def _check_training_quantity(self):
        self.ensure_one()
        order = self.order_id
        product = self.product_id
        basis = product.product_tmpl_id.training_price_basis
        expected_qty = order.training_attendee_count if basis == "person" else 1
        if self.product_uom_id != product.uom_id or self.product_uom_qty != expected_qty:
            raise ValidationError(
                self.env._("The training line quantity must match its per-person or package price basis.")
            )

        return True
