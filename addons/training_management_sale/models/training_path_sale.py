"""P09 commercial contracts use native order lines and the existing learning records."""

from odoo import api, fields, models
from odoo.exceptions import AccessError, ValidationError

from odoo.addons.training_management.models.training_controlled import TERMINAL
from .training_allocation import SaleOrder as AllocationOrder

COORDINATOR = "training_management.group_training_coordinator"


class SaleOrder(models.Model):
    _inherit = "sale.order"  # pylint: disable=consider-merging-classes-inherited

    training_path_id = fields.Many2one("training.path", ondelete="restrict", check_company=True, copy=True)
    training_path_label = fields.Char(readonly=True, copy=False)
    training_agreed_at = fields.Datetime(readonly=True, copy=False)
    training_path_scope = fields.Selection(
        [("complete", "Complete Path"), ("selection", "Selected Courses")], copy=True
    )
    training_price_source = fields.Selection(
        [
            ("pricelist", "Native Pricelist"),
            ("quote", "Price Agreed on Quotation"),
        ],
        copy=True,
        help="Commercial origin only; prices and discounts follow native Odoo rules.",
    )
    training_path_usage_ids = fields.One2many(
        "training.path.sale.usage",
        "order_id",
        readonly=True,
        copy=False,
        groups=COORDINATOR,
    )

    @api.model_create_multi
    def create(self, vals_list):
        values = []
        for vals in vals_list:
            vals = dict(vals)
            vals.pop("training_path_label", None)
            vals["training_agreed_at"] = False
            vals["training_path_label"] = False
            path_id = vals.get("training_path_id") or self.env.context.get("default_training_path_id")
            path = self.env["training.path"].browse(path_id)
            if path_id:
                vals["training_path_id"] = path_id
            if path:
                path.check_access("read")
                vals.update(
                    training_path_label=path.name, training_path_scope=vals.get("training_path_scope") or "complete"
                )
            values.append(vals)
        orders = super().create(values)
        for order in orders.filtered(
            lambda item: item.state == "sale" and (item.training_path_id or item.training_price_source == "quote")
        ):
            super(SaleOrder, order).write({"training_agreed_at": fields.Datetime.now()})  # pylint: disable=super-method-mismatch
        return orders

    def write(self, vals):
        if {"training_path_label", "training_agreed_at"} & vals.keys():
            raise ValidationError(self.env._("The quoted path label is generated by the server."))
        terms = {
            "training_path_id",
            "training_path_scope",
            "training_price_source",
            "training_attendee_count",
            "training_request_kind",
            "training_requested_program_id",
            "training_requested_currency_id",
            "currency_id",
            "pricelist_id",
            "partner_id",
            "company_id",
        }
        with self.env.cr.savepoint():
            self.check_access("write")
            self.lock_for_update()
            self.invalidate_recordset()
            if {"training_path_id", "training_path_scope", "training_price_source"} & vals.keys() and any(
                order.state == "sale" for order in self
            ):
                raise ValidationError(self.env._("Revise the accepted training offer instead of changing its terms."))
            if terms & vals.keys() and any(o.training_agreed_at for o in self):
                raise ValidationError(self.env._("Revise the accepted training offer instead of changing its terms."))
            if "training_path_id" in vals and any(o.order_line.filtered("training_path_step_id") for o in self):
                raise ValidationError(self.env._("Remove draft path lines before choosing another path."))
            if vals.get("state") == "cancel":
                usages = (
                    self.env["training.path.sale.usage"]
                    .sudo()
                    .search(
                        [
                            ("order_id", "in", self.ids),
                            ("withdrawn_at", "=", False),
                        ]
                    )
                )
                if usages:
                    raise ValidationError(
                        self.env._("Withdraw commercial path references before cancelling the order.")
                    )
            result = super().write(vals)
            if vals.get("state") == "sale":
                for order in self.filtered(
                    lambda item: (
                        not item.training_agreed_at and (item.training_path_id or item.training_price_source == "quote")
                    )
                ):
                    super(SaleOrder, order).write({"training_agreed_at": fields.Datetime.now()})  # pylint: disable=super-method-mismatch
            if "training_path_id" in vals:
                for order in self:
                    super(SaleOrder, order).write({"training_path_label": order.training_path_id.name or False})  # pylint: disable=super-method-mismatch
            return result

    @api.private
    def _check_training_offer(self):
        ordinary = self.filtered(lambda order: not order.training_path_id)
        super(SaleOrder, ordinary)._check_training_offer()
        for order in self - ordinary:
            path = order.training_path_id
            lines = order.order_line.filtered("training_program_id")
            if path.state != "validated" or path.company_id != order.company_id:
                raise ValidationError(self.env._("Choose a validated path from this operating company."))
            if order.training_requested_program_id or order.training_request_kind not in ("individual", "group"):
                raise ValidationError(self.env._("Qualify the path request without a single requested programme."))
            if order.training_attendee_count <= 0 or (
                order.training_request_kind == "individual" and order.training_attendee_count != 1
            ):
                raise ValidationError(self.env._("Set a positive group size or one individual beneficiary."))
            if not lines or order.training_path_scope not in ("complete", "selection"):
                raise ValidationError(self.env._("Select at least one course and the path scope."))
            lines._check_path_step()
            if order.training_path_scope == "complete" and set(lines.training_path_step_id.ids) != set(
                path.step_ids.ids
            ):
                raise ValidationError(self.env._("A complete path offer must contain every path course exactly once."))
            lines._check_training_program()
            for line in lines:
                line._check_training_quantity()
        return True

    @api.private
    def _path_contract_lock(self):
        self.check_access("read")
        self.sorted("id").lock_for_update()
        self.invalidate_recordset()
        for order in self:
            # Same MVCC fence as existing commercial allocations. A stale
            # snapshot must retry the whole transaction before counting people.
            super(AllocationOrder, order).write(  # pylint: disable=super-method-mismatch
                {"training_allocation_revision": order.training_allocation_revision + 1}
            )
        return True

    @api.private
    def _check_path_beneficiaries(self):
        for order in self:
            if not order.training_path_id:
                continue
            order._path_contract_lock()
            # Count exact native contacts, never company membership or logins.
            enrollments = (
                self.env["training.enrollment"]
                .sudo()
                .search(
                    [
                        ("allocation_id.sale_line_id.order_id", "=", order.id),
                    ]
                )
            )
            participants = enrollments.filtered(
                lambda e: e.state not in TERMINAL or e.state == "closed" or e.access_start
            ).participant_id
            usages = (
                self.env["training.path.sale.usage"]
                .sudo()
                .search(
                    [
                        ("order_id", "=", order.id),
                        ("withdrawn_at", "=", False),
                        ("reference_id.withdrawn_at", "=", False),
                    ]
                )
            )
            participants |= usages.reference_id.participant_id
            if len(participants) > order.training_attendee_count:
                raise ValidationError(self.env._("The distinct beneficiaries exceed the contracted path group size."))

    def action_prepare_training_path(self):
        self.ensure_one()
        self.check_access("write")
        if self.state != "draft" or self.order_line.filtered("training_program_id"):
            raise ValidationError(self.env._("Prepare the path on a draft quotation without training lines."))
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("Prepare Path Quotation"),
            "res_model": "training.path.quote",
            "view_mode": "form",
            "target": "new",
            "context": {"default_order_id": self.id},
        }

    def action_reuse_path_achievement(self):
        self.ensure_one()
        self.check_access("read")
        self.env["training.path.sale.usage"]._require_coordinator()
        if self.state != "sale" or not self.training_path_id:
            raise ValidationError(self.env._("Reuse acquired work on a confirmed path contract."))
        return {
            "type": "ir.actions.act_window",
            "name": self.env._("Reuse Prior Learning"),
            "res_model": "training.path.reuse",
            "view_mode": "form",
            "target": "new",
            "context": {"default_order_id": self.id},
        }


class SaleOrderLine(models.Model):
    _inherit = "sale.order.line"  # pylint: disable=consider-merging-classes-inherited

    training_path_step_id = fields.Many2one("training.path.step", ondelete="restrict", check_company=True, copy=True)
    _one_path_step = models.UniqueIndex(
        "(order_id, training_path_step_id) WHERE training_path_step_id IS NOT NULL", "Quote each path course only once."
    )

    @api.constrains("training_path_step_id", "training_program_id", "order_id", "product_id", "is_downpayment")
    def _check_path_step(self):
        for line in self:
            step = line.training_path_step_id
            if line.is_downpayment and (step or line.training_program_id):
                raise ValidationError(self.env._("A training course cannot be disguised as a down-payment line."))
            if not line.training_program_id and not step:
                continue
            if line.order_id.training_path_id:
                if (
                    not step
                    or step.path_id != line.order_id.training_path_id
                    or step.program_id != line.training_program_id
                ):
                    raise ValidationError(self.env._("Each path line must use its exact selected step and programme."))
            elif step:
                raise ValidationError(self.env._("Choose a path contract before setting a path step."))

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            order = self.env["sale.order"].browse(vals.get("order_id") or self.env.context.get("default_order_id"))
            order.check_access("read")
            if order.training_path_id or order.training_price_source == "quote":
                order.lock_for_update()
                order.invalidate_recordset()
            if order.training_agreed_at and not (
                vals.get("is_downpayment")
                and not vals.get("training_program_id")
                and not vals.get("training_path_step_id")
                and not self.env["product.product"].browse(vals.get("product_id")).product_tmpl_id.training_course_id
            ):
                raise ValidationError(self.env._("Revise the accepted offer before adding commercial lines."))
        return super().create(vals_list)

    def write(self, vals):
        commercial = {
            "order_id",
            "product_id",
            "product_uom_qty",
            "product_uom_id",
            "price_unit",
            "discount",
            "training_program_id",
            "training_path_step_id",
            "name",
            "display_type",
            "tax_ids",
            "is_downpayment",
        }
        with self.env.cr.savepoint():
            self.check_access("write")
            orders = self.order_id
            if vals.get("order_id"):
                destination = self.env["sale.order"].browse(vals["order_id"])
                destination.check_access("read")
                orders |= destination
            orders = orders.filtered(lambda order: order.training_path_id or order.training_price_source == "quote")
            orders.sorted("id").lock_for_update()
            orders.invalidate_recordset()
            downpayment_identity = {
                "order_id",
                "product_id",
                "training_program_id",
                "training_path_step_id",
                "is_downpayment",
                "display_type",
            }
            if downpayment_identity & vals.keys() and any(order.training_agreed_at for order in orders):
                raise ValidationError(self.env._("Revise the accepted training offer instead of changing its lines."))
            if commercial & vals.keys() and any(
                item.order_id.training_agreed_at and (not item.is_downpayment or item.training_program_id)
                for item in self
            ):
                raise ValidationError(self.env._("Revise the accepted training offer instead of changing its lines."))
            return super().write(vals)

    @api.ondelete(at_uninstall=False)
    def _unlink_accepted_path(self):
        orders = self.order_id.filtered(lambda order: order.training_path_id or order.training_price_source == "quote")
        orders.lock_for_update()
        orders.invalidate_recordset()
        if any(
            item.order_id.training_agreed_at and (not item.is_downpayment or item.training_program_id) for item in self
        ):
            raise ValidationError(self.env._("Keep accepted training lines and their history."))


class TrainingEnrollment(models.Model):
    _inherit = "training.enrollment"  # pylint: disable=consider-merging-classes-inherited

    @api.private
    def _check_identity(self):
        result = super()._check_identity()
        # Narrow existence check only: standalone S03 requests keep their
        # original permissions. Path contracts still require native Sales read.
        orders = self.allocation_id.sudo().sale_line_id.order_id.filtered("training_path_id").with_env(self.env)
        orders._check_path_beneficiaries()
        return result

    @api.model_create_multi
    def create(self, vals_list):
        with self.env.cr.savepoint():
            enrollments = super().create(vals_list)
            for enrollment in enrollments:
                orders = (
                    enrollment.allocation_id.sudo()
                    .sale_line_id.order_id.filtered("training_path_id")
                    .with_env(self.env)
                )
                if not orders:
                    continue
                orders.check_access("read")
                line = enrollment.allocation_id.sale_line_id
                reference = self.env["training.path.assignment"].search(
                    [
                        ("step_id", "=", line.training_path_step_id.id),
                        ("participant_id", "=", enrollment.participant_id.id),
                        ("withdrawn_at", "=", False),
                    ]
                )
                if reference:
                    raise ValidationError(
                        self.env._("Reuse the existing path reference or withdraw it before a new enrollment.")
                    )
                reference = self.env["training.path.assignment"].create(
                    {"step_id": line.training_path_step_id.id, "enrollment_id": enrollment.id}
                )
                self.env["training.path.sale.usage"].create(
                    {"order_id": line.order_id.id, "reference_id": reference.id}
                )
            return enrollments


class TrainingPathSaleUsage(models.Model):
    _name = "training.path.sale.usage"
    _inherit = "training.controlled"
    _description = "Commercial Reference to Existing Path Work"
    _check_company_auto = True
    _rec_name = "reference_id"
    _reason_actions = ("action_withdraw",)

    order_id = fields.Many2one("sale.order", required=True, ondelete="restrict", check_company=True, index=True)
    reference_id = fields.Many2one("training.path.assignment", required=True, ondelete="restrict", check_company=True)
    company_id = fields.Many2one(related="order_id.company_id", store=True)
    delivery_id = fields.Many2one(related="reference_id.delivery_id", store=True)
    recorded_by_id = fields.Many2one("res.users", readonly=True, ondelete="restrict")
    recorded_at = fields.Datetime(readonly=True)
    withdrawn_at = fields.Datetime(readonly=True)
    withdrawn_by_id = fields.Many2one("res.users", readonly=True, ondelete="restrict")
    withdrawal_reason = fields.Text(readonly=True)
    _one_current_usage = models.UniqueIndex(
        "(order_id, reference_id) WHERE withdrawn_at IS NULL", "This path reference already belongs to the contract."
    )

    @api.model_create_multi
    def create(self, vals_list):
        self._require_coordinator()
        with self.env.cr.savepoint():
            values = []
            for vals in vals_list:
                if set(vals) - {"order_id", "reference_id"}:
                    raise ValidationError(self.env._("Commercial reference metadata is generated by the server."))
                order = self.env["sale.order"].browse(vals.get("order_id"))
                reference = self.env["training.path.assignment"].browse(vals.get("reference_id"))
                reference._require_coordinator()
                reference.delivery_id._serialize()
                order._path_contract_lock()
                if (
                    order.state != "sale"
                    or not order.training_path_id
                    or reference.withdrawn_at
                    or reference.path_id != order.training_path_id
                    or reference.company_id != order.company_id
                ):
                    raise ValidationError(self.env._("Choose a current reference from this confirmed path contract."))
                line = order.order_line.filtered(lambda item: item.training_path_step_id == reference.step_id)
                if len(line) != 1:
                    raise ValidationError(self.env._("The acquired course must be included in the commercial offer."))
                enrollment = reference.enrollment_id
                if enrollment.allocation_id.sale_line_id != line and not reference._is_completed():
                    raise ValidationError(
                        self.env._("Only completed prior learning can replace a new contracted enrollment.")
                    )
                if self.search_count(
                    [("order_id", "=", order.id), ("reference_id", "=", reference.id), ("withdrawn_at", "=", False)]
                ):
                    raise ValidationError(self.env._("This path reference already belongs to the contract."))
                values.append(
                    dict(
                        vals,
                        recorded_by_id=self.env.uid,
                        recorded_at=fields.Datetime.now(),
                        withdrawn_at=False,
                        withdrawn_by_id=False,
                        withdrawal_reason=False,
                    )
                )
            result = super().create(values)
            result.order_id._check_path_beneficiaries()
            return result

    def write(self, vals):  # pylint: disable=method-required-super
        raise AccessError(self.env._("Commercial path references are immutable; withdraw them with a reason."))

    @api.private
    def _reason_labels(self):
        return {"action_withdraw": self.env._("Withdraw Commercial Path Reference")}

    def action_withdraw(self, reason=None):
        with self.env.cr.savepoint():
            self._require_coordinator()
            self.delivery_id._serialize()
            self.order_id._path_contract_lock()
            self.invalidate_recordset()
            for usage in self:
                if not usage.withdrawn_at:
                    usage._store(
                        {
                            "withdrawn_at": fields.Datetime.now(),
                            "withdrawn_by_id": self.env.uid,
                            "withdrawal_reason": self._require_reason(reason),
                        },
                        reason,
                    )
        return True
